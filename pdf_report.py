import pandas as pd
from pathlib import Path
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER, TA_LEFT
from reportlab.lib.units import inch

from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    PageBreak
)


class PDFReportGenerator:

    def __init__(self):

        self.input_file = Path(
            "output/cleaned_sales_data.xlsx"
        )

        self.output_folder = Path("reports")
        self.output_folder.mkdir(exist_ok=True)

        self.output_file = (
            self.output_folder /
            "Automated_Sales_Report.pdf"
        )

        self.styles = getSampleStyleSheet()

    def load_data(self):
        """Load cleaned sales dataset."""

        if not self.input_file.exists():
            raise FileNotFoundError(
                "Cleaned sales data not found!"
            )

        df = pd.read_excel(self.input_file)

        if df.empty:
            raise ValueError("No sales data available!")

        return df

    def create_styles(self):

        self.title_style = ParagraphStyle(
            "ReportTitle",
            parent=self.styles["Title"],
            fontSize=23,
            textColor=colors.HexColor("#17365D"),
            alignment=TA_CENTER,
            spaceAfter=15
        )

        self.heading_style = ParagraphStyle(
            "SectionHeading",
            parent=self.styles["Heading2"],
            fontSize=14,
            textColor=colors.HexColor("#1F4E78"),
            spaceBefore=15,
            spaceAfter=8
        )

        self.normal_style = ParagraphStyle(
            "ReportBody",
            parent=self.styles["Normal"],
            fontSize=10,
            leading=15
        )

    def create_table(self, data, column_widths=None):
        """Create professionally formatted PDF tables."""

        table = Table(
            data,
            colWidths=column_widths,
            repeatRows=1
        )

        table.setStyle(TableStyle([

            ("BACKGROUND", (0, 0), (-1, 0),
             colors.HexColor("#17365D")),

            ("TEXTCOLOR", (0, 0), (-1, 0),
             colors.white),

            ("FONTNAME", (0, 0), (-1, 0),
             "Helvetica-Bold"),

            ("FONTSIZE", (0, 0), (-1, -1), 9),

            ("ALIGN", (0, 0), (-1, -1), "CENTER"),

            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),

            ("ROWBACKGROUNDS", (0, 1), (-1, -1),
             [
                 colors.white,
                 colors.HexColor("#EAF2F8")
             ]),

            ("GRID", (0, 0), (-1, -1),
             0.5, colors.HexColor("#D5DDE5")),

            ("TOPPADDING", (0, 0), (-1, -1), 8),

            ("BOTTOMPADDING", (0, 0), (-1, -1), 8)

        ]))

        return table

    def add_footer(self, canvas, document):
        """Add page number and footer."""

        canvas.saveState()

        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(colors.grey)

        canvas.drawString(
            40, 25,
            "Automated Sales Report | Generated by Python"
        )

        canvas.drawRightString(
            A4[0] - 40,
            25,
            f"Page {document.page}"
        )

        canvas.restoreState()

    def generate_report(self, df):

        self.create_styles()

        story = []

        # Report title
        story.append(Spacer(1, 35))

        story.append(Paragraph(
            "AUTOMATED SALES REPORT",
            self.title_style
        ))

        story.append(Paragraph(
            "Business Performance and Sales Analysis",
            ParagraphStyle(
                "Subtitle",
                parent=self.styles["Normal"],
                alignment=TA_CENTER,
                fontSize=12,
                textColor=colors.grey
            )
        ))

        story.append(Spacer(1, 20))

        story.append(Paragraph(
            f"Report Generated: "
            f"{datetime.now().strftime('%d-%m-%Y %H:%M')}",
            self.normal_style
        ))

        story.append(Spacer(1, 20))

        # Executive Summary
        total_revenue = df["Total_Sales"].sum()
        total_orders = len(df)
        total_quantity = df["Quantity"].sum()

        average_order = (
            total_revenue / total_orders
            if total_orders else 0
        )

        top_product = (
            df.groupby("Product")["Total_Sales"]
            .sum()
            .idxmax()
        )

        story.append(Paragraph(
            "1. EXECUTIVE SUMMARY",
            self.heading_style
        ))

        summary_data = [
            ["Metric", "Value"],
            ["Total Revenue", f"Rs. {total_revenue:,.2f}"],
            ["Total Orders", str(total_orders)],
            ["Total Quantity Sold", str(total_quantity)],
            ["Average Order Value", f"Rs. {average_order:,.2f}"],
            ["Top Performing Product", str(top_product)]
        ]

        story.append(self.create_table(
            summary_data,
            [3 * inch, 3 * inch]
        ))

        # Product analysis
        story.append(Paragraph(
            "2. PRODUCT-WISE SALES ANALYSIS",
            self.heading_style
        ))

        product_data = (
            df.groupby("Product")["Total_Sales"]
            .sum()
            .sort_values(ascending=False)
        )

        product_table = [
            ["Product", "Total Revenue"]
        ]

        for product, sales in product_data.items():

            product_table.append([
                str(product),
                f"Rs. {sales:,.2f}"
            ])

        story.append(self.create_table(
            product_table,
            [3 * inch, 3 * inch]
        ))

        # Category analysis
        story.append(Paragraph(
            "3. CATEGORY-WISE SALES ANALYSIS",
            self.heading_style
        ))

        category_data = (
            df.groupby("Category")["Total_Sales"]
            .sum()
            .sort_values(ascending=False)
        )

        category_table = [
            ["Category", "Total Revenue"]
        ]

        for category, sales in category_data.items():

            category_table.append([
                str(category),
                f"Rs. {sales:,.2f}"
            ])

        story.append(self.create_table(
            category_table,
            [3 * inch, 3 * inch]
        ))

        # Region analysis
        story.append(Paragraph(
            "4. REGION-WISE SALES ANALYSIS",
            self.heading_style
        ))

        region_data = (
            df.groupby("Region")["Total_Sales"]
            .sum()
            .sort_values(ascending=False)
        )

        region_table = [
            ["Region", "Total Revenue"]
        ]

        for region, sales in region_data.items():

            region_table.append([
                str(region),
                f"Rs. {sales:,.2f}"
            ])

        story.append(self.create_table(
            region_table,
            [3 * inch, 3 * inch]
        ))

        # Monthly analysis
        story.append(Paragraph(
            "5. MONTHLY SALES ANALYSIS",
            self.heading_style
        ))

        df["Date"] = pd.to_datetime(df["Date"])

        monthly_data = (
            df.groupby(df["Date"].dt.strftime("%Y-%m"))
            ["Total_Sales"]
            .sum()
        )

        monthly_table = [
            ["Month", "Total Revenue"]
        ]

        for month, sales in monthly_data.items():

            monthly_table.append([
                str(month),
                f"Rs. {sales:,.2f}"
            ])

        story.append(self.create_table(
            monthly_table,
            [3 * inch, 3 * inch]
        ))

        # Business insights
        story.append(Paragraph(
            "6. BUSINESS INSIGHTS",
            self.heading_style
        ))

        insights = [
            f"Total revenue generated was Rs. {total_revenue:,.2f}.",
            f"A total of {total_orders} orders were recorded.",
            f"The top performing product was {top_product}.",
            f"Total quantity sold was {total_quantity} units.",
            "Product, category and regional performance "
            "are included for business review."
        ]

        for insight in insights:

            story.append(Paragraph(
                f"&bull; {insight}",
                self.normal_style
            ))

            story.append(Spacer(1, 6))

        # Generate PDF
        document = SimpleDocTemplate(
            str(self.output_file),
            pagesize=A4,
            rightMargin=40,
            leftMargin=40,
            topMargin=45,
            bottomMargin=45,
            title="Automated Sales Report",
            author="Python Sales Automation System"
        )

        document.build(
            story,
            onFirstPage=self.add_footer,
            onLaterPages=self.add_footer
        )

    def run(self):

        print("\n" + "=" * 50)
        print("     AUTOMATED PDF REPORT GENERATOR")
        print("=" * 50)

        try:

            df = self.load_data()

            print("Sales data loaded successfully!")

            self.generate_report(df)

            print("\nPDF REPORT GENERATED SUCCESSFULLY!")
            print("-" * 50)
            print(f"Output: {self.output_file}")
            print("Status: Successfully Created!")
            print("=" * 50)

        except Exception as error:

            print(f"\nPDF Generation Error: {error}")


if __name__ == "__main__":

    generator = PDFReportGenerator()
    generator.run()